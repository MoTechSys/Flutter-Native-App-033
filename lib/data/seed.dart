Future<void> seedCatalog(Database d) async {
  final batch = d.batch();
  for (final c in _cats) {
    batch.insert('categories', {
      'id': c.$1,
      'name': c.$2,
      'slug': c.$3,
      'color': c.$4,
    });
  }
  for (final b in _books) {
    final cat = _cats.firstWhere((c) => c.$1 == b.$2);
    batch.insert('books', {
      'id': b.$1,
      'category_id': b.$2,
      'title': b.$3,
      'author': b.$4,
      'price': b.$5,
      'old_price': b.$6,
      'rating': b.$7,
      'pages': b.$8,
      'year': b.$9,
      'featured': b.$10,
      'description': b.$11,
      'cover': 'assets/covers/book_${b.$1}.png',
      'cover_color': cat.$4,
    });
  }
  await batch.commit(noResult: true);
}
